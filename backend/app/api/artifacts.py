"""
Artifact download endpoints: PDF/TXT of a stage's output and ZIPs of generated files.

Read-only: everything is built in memory from the stored execution results, which are
never modified. Export failures return an error for the download only.
"""
import uuid
from typing import Literal
from urllib.parse import quote

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import Response
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload
from starlette.concurrency import run_in_threadpool

from backend.app.api.execution import get_execution_details
from backend.app.artifacts.document import ExportError
from backend.app.artifacts.pdf_generator import render_pdf
from backend.app.artifacts.service import record_artifact
from backend.app.artifacts.txt_generator import render_txt_bytes
from backend.app.artifacts.zip_generator import build_zip, safe_filename
from backend.app.core.dependencies import get_current_active_user
from backend.app.core.ownership import owned_workflow_ids
from backend.app.database import get_db
from backend.app.models.user import User
from backend.app.models.execution import ExecutionRecord

router = APIRouter(tags=["artifacts"])

MEDIA_TYPES = {"pdf": "application/pdf", "txt": "text/plain; charset=utf-8", "zip": "application/zip"}


def _download(content: bytes, filename: str, kind: str) -> Response:
    ascii_name = filename.encode("ascii", "replace").decode().replace("?", "_").replace('"', "_")
    return Response(content=content, media_type=MEDIA_TYPES[kind], headers={
        "Content-Disposition": f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename)}",
    })


async def _stage_record(
    db: AsyncSession, execution_id: uuid.UUID, stage_id: uuid.UUID, user: User
) -> ExecutionRecord:
    """The stage's record in that execution, only if the execution's workflow is owned by `user`."""
    result = await db.execute(
        select(ExecutionRecord)
        .options(selectinload(ExecutionRecord.stage))
        .where(
            ExecutionRecord.execution_id == execution_id,
            ExecutionRecord.stage_id == stage_id,
            ExecutionRecord.workflow_id.in_(owned_workflow_ids(user.id)),
        )
        .order_by(ExecutionRecord.created_at.desc())
        .limit(1)
    )
    record = result.scalar_one_or_none()
    if record is None:
        raise HTTPException(status_code=404, detail="Stage not found in this execution")
    return record


@router.get("/executions/{execution_id}/stages/{stage_id}/document")
async def download_stage_document(
    execution_id: uuid.UUID,
    stage_id: uuid.UUID,
    format: Literal["pdf", "txt"] = Query("pdf", description="pdf or txt"),
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    """A completed stage's output as a PDF or plain-text document."""
    record = await _stage_record(db, execution_id, stage_id, current_user)
    if record.status != "completed" or not (record.result or "").strip():
        raise HTTPException(status_code=404, detail="This stage has no output to download")
    title = record.stage.name if record.stage else "Stage output"
    try:
        if format == "pdf":
            content = await run_in_threadpool(render_pdf, record.result, title)
        else:
            content = render_txt_bytes(record.result, title)
    except ExportError as e:
        raise HTTPException(status_code=422, detail=f"Could not create {format.upper()}: {e}")
    return _download(content, f"{safe_filename(title, 'output')}.{format}", format)


@router.get("/executions/{execution_id}/stages/{stage_id}/artifact.zip")
async def download_stage_zip(
    execution_id: uuid.UUID,
    stage_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    """The files generated by one stage, as a ZIP that keeps their folder structure."""
    artifact = record_artifact(await _stage_record(db, execution_id, stage_id, current_user))
    if artifact is None or not artifact.files:
        raise HTTPException(status_code=404, detail="This stage did not generate files")
    try:
        content = build_zip(artifact)
    except ExportError as e:
        raise HTTPException(status_code=422, detail=f"Could not create ZIP: {e}")
    return _download(content, f"{safe_filename(artifact.name, 'project')}.zip", "zip")


@router.get("/executions/{execution_id}/artifact.zip")
async def download_execution_zip(
    execution_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    """The project combining files from several stages of an execution, as a ZIP."""
    details = await get_execution_details(execution_id, db, current_user)
    if details.artifact is None:
        raise HTTPException(status_code=404, detail="This execution has no combined project")
    try:
        content = build_zip(details.artifact)
    except ExportError as e:
        raise HTTPException(status_code=422, detail=f"Could not create ZIP: {e}")
    return _download(content, f"{safe_filename(details.artifact.name, 'project')}.zip", "zip")
