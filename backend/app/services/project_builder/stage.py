"""
The "project_build" workflow stage.

A Complete Project workflow ends with one stage whose config has kind = "project_build".
It depends on the file-generating stages; the execution engine runs it instead of an LLM
call (see ExecutionEngine._run_project_build), so it gets DAG ordering, live status over
the WebSocket, pause/cancel and model routing (for repair calls) like any other stage.
"""
import uuid
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from backend.app.models.execution import ExecutionRecord
from backend.app.models.stage import Stage
from backend.app.services.project_builder.extraction import extract_project_files, merge_stage_files

PROJECT_BUILD_KIND = "project_build"


def is_project_build_stage(stage: Stage) -> bool:
    return (stage.config or {}).get("kind") == PROJECT_BUILD_KIND


async def collect_project_files(db: AsyncSession, execution_id: uuid.UUID,
                                stage: Stage) -> tuple[list[dict], list[str]]:
    """
    The files generated by the build stage's upstream stages in this execution, in stage
    order (a later stage replaces an earlier stage's file at the same path), plus warnings
    about anything that could not be used. Extraction is lenient (see extraction.py), so a
    truncated answer still contributes its complete files.
    """
    upstream = [d.depends_on_stage_id for d in stage.dependencies]
    if not upstream:
        return [], []
    records = (await db.execute(
        select(ExecutionRecord)
        .options(selectinload(ExecutionRecord.stage))
        .where(ExecutionRecord.execution_id == execution_id,
               ExecutionRecord.stage_id.in_(upstream),
               ExecutionRecord.status == "completed")
    )).scalars().all()
    records = sorted(records, key=lambda r: (r.stage.stage_order if r.stage else 0, r.created_at))
    per_stage, warnings = [], []
    for record in records:
        label = record.stage.name if record.stage else "stage"
        files, more = extract_project_files(record.result)
        per_stage.append((label, files))
        warnings += [f"{label}: {w}" for w in more]
    files, more = merge_stage_files(per_stage)
    return files, warnings + more
