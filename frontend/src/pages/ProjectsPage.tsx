/**
 * The user's generated projects: status of the latest build, and downloads without regenerating.
 */
import { useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { Boxes, Download, Plus, CheckCircle2, XCircle, Wrench } from 'lucide-react';
import { projectsApi, type Project } from '../api/projectsApi';
import { PageHeader } from '../components/ui/PageHeader';
import { StatusBadge } from '../components/ui/StatusBadge';
import { EmptyState, ErrorState, Skeleton } from '../components/ui/States';
import { MetricCard } from '../components/metrics/MetricCard';
import { DownloadError, useDownload } from '../components/results/ArtifactOutput';
import { getErrorMessage } from '../lib/errors';
import { safeFileStem } from '../lib/download';
import { relativeTime } from '../lib/format';

export default function ProjectsPage() {
  const [projects, setProjects] = useState<Project[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const { busy, error: downloadError, run: download } = useDownload();

  const load = () => {
    setError(null);
    projectsApi.list()
      .then(setProjects)
      .catch((err: unknown) => setError(getErrorMessage(err)));
  };

  useEffect(load, []);

  const counts = useMemo(() => {
    const list = projects ?? [];
    return {
      total: list.length,
      succeeded: list.filter((p) => p.status === 'succeeded').length,
      failed: list.filter((p) => p.status === 'failed').length,
      repairs: list.reduce((n, p) => n + (p.latest_run?.repairs.length ?? 0), 0),
    };
  }, [projects]);

  return (
    <div>
      <PageHeader
        eyebrow="Build"
        title="Projects"
        description="Complete projects generated by your workflows, with their latest build result."
        actions={<Link to="/" className="btn btn-primary"><Plus size={16} aria-hidden /> New project</Link>}
      />
      <DownloadError message={downloadError} />
      {error && <ErrorState title="Could not load projects" message={error} onRetry={load} />}
      {!projects && !error && (
        <div className="space-y-3" aria-busy>
          <Skeleton className="h-12" /><Skeleton className="h-12" /><Skeleton className="h-12" />
        </div>
      )}
      {projects?.length === 0 && (
        <EmptyState
          icon={Boxes}
          title="No projects yet."
          description={<>Choose <span className="font-book text-ink">Complete project</span> when planning a workflow. Its files are installed, built and tested in a sandbox, with automatic fixes.</>}
          action={<Link to="/" className="btn btn-primary"><Plus size={16} aria-hidden /> Plan a project</Link>}
        />
      )}
      {projects && projects.length > 0 && (
        <>
          <div className="mb-6 grid grid-cols-2 gap-3 lg:grid-cols-4">
            <MetricCard icon={Boxes} label="Projects" value={String(counts.total)} />
            <MetricCard icon={CheckCircle2} label="Build passing" value={String(counts.succeeded)} />
            <MetricCard icon={XCircle} label="Build failing" value={String(counts.failed)} />
            <MetricCard icon={Wrench} label="AI repairs applied" value={String(counts.repairs)} detail="across latest builds" />
          </div>
          <div className="card overflow-x-auto">
            <table className="data-table data-table-hover">
              <thead>
                <tr>
                  <th>Project</th>
                  <th>Status</th>
                  <th className="hidden md:table-cell">Type</th>
                  <th className="hidden !text-right sm:table-cell">Files</th>
                  <th className="hidden !text-right md:table-cell">Repairs</th>
                  <th className="hidden lg:table-cell">Updated</th>
                  <th><span className="sr-only">Download</span></th>
                </tr>
              </thead>
              <tbody>
                {projects.map((p, index) => (
                  <tr key={p.id} className="animate-fade-in-up" style={{ animationDelay: `${Math.min(index, 12) * 0.03}s` }}>
                    <td className="min-w-[8rem] sm:min-w-[10rem]">
                      {p.workflow_id
                        ? <Link to={`/workflows/${p.workflow_id}`} className="font-book text-ink hover:text-primary-700">{p.name}</Link>
                        : <span className="font-book text-ink">{p.name}</span>}
                      <p className="mt-0.5 text-xs text-ink-muted lg:hidden">{relativeTime(p.updated_at)}</p>
                    </td>
                    <td><StatusBadge status={p.status} /></td>
                    <td className="hidden font-mono text-xs text-ink-secondary md:table-cell">{p.project_type ?? '—'}</td>
                    <td className="hidden text-right tabular sm:table-cell">{p.file_count}</td>
                    <td className="hidden text-right tabular md:table-cell">{p.latest_run?.repairs.length ?? 0}</td>
                    <td className="hidden whitespace-nowrap text-ink-secondary lg:table-cell" title={new Date(p.updated_at).toLocaleString()}>
                      {new Date(p.updated_at).toLocaleString()}
                    </td>
                    <td className="text-right">
                      <button type="button" className="btn btn-outline btn-sm" disabled={busy !== null || p.file_count === 0}
                              aria-label={`Download ${p.name} as ZIP`}
                              onClick={() => download(p.id, () => projectsApi.download(p.id), `${safeFileStem(p.name, 'project')}.zip`)}>
                        <Download size={13} aria-hidden />
                        <span className="hidden sm:inline">{busy === p.id ? 'Preparing…' : 'ZIP'}</span>
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      )}
    </div>
  );
}
