/**
 * The user's generated projects: status of the latest build, and downloads without regenerating.
 */
import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Boxes, Download, Plus } from 'lucide-react';
import { projectsApi, type Project } from '../api/projectsApi';
import { PageHeader } from '../components/ui/PageHeader';
import { StatusBadge } from '../components/ui/StatusBadge';
import { DownloadError, useDownload } from '../components/results/ArtifactOutput';
import { getErrorMessage } from '../lib/errors';
import { safeFileStem } from '../lib/download';

export default function ProjectsPage() {
  const [projects, setProjects] = useState<Project[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const { busy, error: downloadError, run: download } = useDownload();

  useEffect(() => {
    projectsApi.list()
      .then(setProjects)
      .catch((err: unknown) => setError(getErrorMessage(err)));
  }, []);

  return (
    <div>
      <PageHeader
        title="Projects"
        description="Complete projects generated by your workflows, with their latest build result"
        actions={<Link to="/" className="btn btn-primary"><Plus size={16} aria-hidden /> New project</Link>}
      />
      <DownloadError message={downloadError} />
      {error && <p role="alert" className="text-sm text-red-400">Could not load projects: {error}</p>}
      {!projects && !error && <p className="text-sm text-surface-200/50">Loading projects…</p>}
      {projects?.length === 0 && (
        <div className="py-16 text-center text-surface-200/50">
          <Boxes size={40} className="mx-auto mb-4 opacity-30" aria-hidden />
          <p>No projects yet. Choose <span className="text-white">Complete project</span> when planning a workflow.</p>
        </div>
      )}
      {projects && projects.length > 0 && (
        <div className="glass overflow-x-auto rounded-xl">
          <table className="w-full text-sm">
            <thead className="border-b border-surface-700/50 text-xs uppercase tracking-wide text-surface-200/50">
              <tr>
                <th className="px-4 py-3 text-left">Project</th>
                <th className="px-4 py-3 text-left">Status</th>
                <th className="px-4 py-3 text-left">Type</th>
                <th className="px-4 py-3 text-right">Files</th>
                <th className="px-4 py-3 text-right">Repairs</th>
                <th className="whitespace-nowrap px-4 py-3 text-left">Updated</th>
                <th className="px-4 py-3"><span className="sr-only">Download</span></th>
              </tr>
            </thead>
            <tbody>
              {projects.map((p) => (
                <tr key={p.id} className="border-b border-surface-700/30">
                  <td className="px-4 py-3">
                    {p.workflow_id
                      ? <Link to={`/workflows/${p.workflow_id}`} className="font-medium hover:text-primary-400">{p.name}</Link>
                      : <span className="font-medium">{p.name}</span>}
                  </td>
                  <td className="px-4 py-3"><StatusBadge status={p.status} /></td>
                  <td className="px-4 py-3 text-surface-200/70">{p.project_type ?? '—'}</td>
                  <td className="px-4 py-3 text-right tabular-nums">{p.file_count}</td>
                  <td className="px-4 py-3 text-right tabular-nums">{p.latest_run?.repairs.length ?? 0}</td>
                  <td className="whitespace-nowrap px-4 py-3 text-surface-200/70">{new Date(p.updated_at).toLocaleString()}</td>
                  <td className="px-4 py-3 text-right">
                    <button type="button" className="btn btn-ghost py-1" disabled={busy !== null || p.file_count === 0}
                            aria-label={`Download ${p.name} as ZIP`}
                            onClick={() => download(p.id, () => projectsApi.download(p.id), `${safeFileStem(p.name, 'project')}.zip`)}>
                      <Download size={14} aria-hidden /> {busy === p.id ? 'Preparing…' : 'ZIP'}
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
